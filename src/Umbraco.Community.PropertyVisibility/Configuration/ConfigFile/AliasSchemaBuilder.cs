using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using Umbraco.Cms.Core.Models;
using Umbraco.Community.PropertyVisibility.Services;

namespace Umbraco.Community.PropertyVisibility.Configuration.ConfigFile;

/// <summary>
///     A root node as the alias schema lists it.
/// </summary>
/// <param name="Key">The root node's key.</param>
/// <param name="Name">The root node's name (default culture), when known.</param>
internal sealed record AliasSchemaRoot(Guid Key, string? Name);

/// <summary>
///     Builds the alias schema: the rules file schema with this site's content type, property, tab and group aliases and
///     its root nodes filled in, so an editor completes them and flags a typo while it is typed.
/// </summary>
/// <remarks>
///     Starts from the package's own rules file schema (<c>PropertyVisibility.config-schema.json</c>, embedded), so the
///     structure and descriptions stay the same. Each <c>ContentTypes</c> object lists the content type aliases as its only
///     allowed keys, and each content type allows only its own property and container aliases, its compositions'
///     included. <c>RootNodeKey</c> and <c>RootNodeName</c> list the root nodes. Values use <c>enum</c> (JSON schema
///     draft 04, like the base schema) with <c>enumDescriptions</c>, which Visual Studio Code shows in its completion
///     list and other editors ignore. The output depends only on its input: everything is sorted and nothing carries a
///     time, so an unchanged site gives an identical file.
/// </remarks>
internal static class AliasSchemaBuilder
{
	private const string BaseSchemaResource = "Umbraco.Community.PropertyVisibility.PropertyVisibility.config-schema.json";

	private static readonly Lazy<string> EmbeddedBaseSchema = new(() =>
	{
		using Stream stream = typeof(AliasSchemaBuilder).Assembly.GetManifestResourceStream(BaseSchemaResource)
			?? throw new InvalidOperationException($"The embedded resource {BaseSchemaResource} is missing.");
		using var reader = new StreamReader(stream);
		return reader.ReadToEnd();
	});

	private static readonly JsonSerializerOptions Output = new()
	{
		WriteIndented = true,
		IndentSize = 2,
		NewLine = "\n",
		// Names with accents or quotes stay readable; the file is only read by editors.
		Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
	};

	/// <summary>
	///     Builds the schema from the package's embedded rules file schema.
	/// </summary>
	/// <param name="contentTypes">The document and element types.</param>
	/// <param name="roots">The content root nodes.</param>
	/// <returns>The schema as indented JSON, ending with a line break.</returns>
	internal static string Build(IEnumerable<IContentType> contentTypes, IEnumerable<AliasSchemaRoot> roots)
		=> Build(EmbeddedBaseSchema.Value, contentTypes, roots);

	/// <summary>
	///     Builds the schema from <paramref name="baseSchema" />.
	/// </summary>
	/// <param name="baseSchema">The rules file schema to fill in.</param>
	/// <param name="contentTypes">The document and element types.</param>
	/// <param name="roots">The content root nodes.</param>
	/// <returns>The schema as indented JSON, ending with a line break.</returns>
	internal static string Build(string baseSchema, IEnumerable<IContentType> contentTypes, IEnumerable<AliasSchemaRoot> roots)
	{
		JsonObject schema = JsonNode.Parse(baseSchema)!.AsObject();
		JsonObject definitions = schema["definitions"]!.AsObject();
		JsonObject baseRule = definitions["ContentTypeVisibilityOptions"]!.AsObject();

		schema["title"] = "PropertyVisibilityConfigFile (aliases of this site)";
		schema["description"] =
			"Generated by Umbraco.Community.PropertyVisibility in the Development environment from this site's document types, "
			+ "element types and root nodes, and rewritten when they change; do not edit it. Aliases must match exactly here, "
			+ "while the package itself matches them case-insensitively. "
			+ (string?)schema["description"];

		IContentType[] types = contentTypes
			.Where(contentType => !string.IsNullOrWhiteSpace(contentType.Alias))
			.OrderBy(contentType => contentType.Alias, StringComparer.OrdinalIgnoreCase)
			.ThenBy(contentType => contentType.Alias, StringComparer.Ordinal)
			.DistinctBy(contentType => contentType.Alias, StringComparer.OrdinalIgnoreCase)
			.ToArray();

		foreach (IContentType contentType in types)
		{
			definitions[DefinitionName(contentType.Alias)] = ContentTypeDefinition(contentType, baseRule);
		}

		RestrictContentTypeKeys(schema["properties"]!["ContentTypes"]!.AsObject(), types);
		RestrictContentTypeKeys(definitions["RuleSetOptions"]!["properties"]!["ContentTypes"]!.AsObject(), types);

		JsonObject siteProperties = definitions["SiteVisibilityOptions"]!["properties"]!.AsObject();
		RestrictContentTypeKeys(siteProperties["ContentTypes"]!.AsObject(), types);
		ListRootNodes(siteProperties, roots.DistinctBy(root => root.Key).ToArray());

		return schema.ToJsonString(Output) + "\n";
	}

	/// <summary>The definition name of a content type; a JSON pointer escapes it in references.</summary>
	private static string DefinitionName(string alias) => $"ContentType.{alias}";

	private static string Reference(string alias)
		=> "#/definitions/" + DefinitionName(alias).Replace("~", "~0", StringComparison.Ordinal).Replace("/", "~1", StringComparison.Ordinal);

	// Only the site's content type aliases as keys, each with its own definition. The object keeps its description.
	private static void RestrictContentTypeKeys(JsonObject contentTypes, IContentType[] types)
	{
		var properties = new JsonObject();
		foreach (IContentType contentType in types)
		{
			properties[contentType.Alias] = new JsonObject { ["$ref"] = Reference(contentType.Alias) };
		}

		contentTypes["properties"] = properties;
		contentTypes["additionalProperties"] = false;
	}

	private static JsonObject ContentTypeDefinition(IContentType contentType, JsonObject baseRule)
	{
		IReadOnlyList<IContentTypeComposition> compositions = CompositionClosure.Of(contentType);
		PropertyGroup[] groups = contentType.CompositionPropertyGroups.Where(group => group.Alias is not null).ToArray();

		string? Origin(Func<IContentTypeComposition, bool> defines)
			=> defines(contentType) ? null : compositions.FirstOrDefault(defines)?.Alias;

		// Containers: the aliases the rules accept, as the resolver lists them.
		var containers = new List<(string Value, string Description)>();
		foreach (var alias in HiddenFieldsResolver.ConfigurableContainerAliases(contentType))
		{
			PropertyGroup group = groups.First(candidate => string.Equals(candidate.Alias, alias, StringComparison.OrdinalIgnoreCase));
			var separator = alias.IndexOf('/', StringComparison.Ordinal);
			var description = group.Type == PropertyGroupType.Tab
				? $"Tab '{group.Name}'"
				: separator > 0
					? $"Group '{group.Name}' in tab '{alias[..separator]}'"
					: $"Group '{group.Name}' (not in a tab)";
			var origin = Origin(owner => owner.PropertyGroups.Any(own => string.Equals(own.Alias, alias, StringComparison.OrdinalIgnoreCase)));
			containers.Add((group.Alias!, origin is null ? description : $"{description}, from composition {origin}"));
		}

		// Properties: own and composed, with the container each one is in.
		var containerOfProperty = new Dictionary<Guid, string>();
		foreach (PropertyGroup group in groups)
		{
			foreach (IPropertyType property in group.PropertyTypes ?? Enumerable.Empty<IPropertyType>())
			{
				containerOfProperty.TryAdd(property.Key, group.Alias!);
			}
		}

		var properties = new List<(string Value, string Description)>();
		foreach (IPropertyType property in contentType.CompositionPropertyTypes
			.Where(property => !string.IsNullOrWhiteSpace(property.Alias))
			.OrderBy(property => property.Alias, StringComparer.OrdinalIgnoreCase)
			.ThenBy(property => property.Alias, StringComparer.Ordinal)
			.DistinctBy(property => property.Alias, StringComparer.OrdinalIgnoreCase))
		{
			var parts = new List<string> { $"'{property.Name}'" };
			if (containerOfProperty.TryGetValue(property.Key, out var container))
			{
				parts.Add($"in {container}");
			}

			if (property.Mandatory)
			{
				parts.Add("mandatory (hiding it blocks publishing)");
			}

			if (Origin(owner => owner.PropertyTypes.Any(own => string.Equals(own.Alias, property.Alias, StringComparison.OrdinalIgnoreCase))) is { } origin)
			{
				parts.Add($"from composition {origin}");
			}

			properties.Add((property.Alias, string.Join(", ", parts)));
		}

		var kind = contentType.IsElement ? "element type" : "document type";
		var composedOf = compositions.Count == 0 ? string.Empty : $", composed of {string.Join(", ", compositions.Select(composition => composition.Alias))}";

		return new JsonObject
		{
			["type"] = "object",
			["description"] = $"{contentType.Name} ({kind}{composedOf}). What to hide on this content type.",
			["additionalProperties"] = false,
			["properties"] = new JsonObject
			{
				["Properties"] = AliasList((string?)baseRule["properties"]!["Properties"]!["description"], properties),
				["Containers"] = AliasList((string?)baseRule["properties"]!["Containers"]!["description"], containers),
			},
		};
	}

	private static JsonObject AliasList(string? description, List<(string Value, string Description)> values)
	{
		var items = new JsonObject { ["type"] = "string" };
		var list = new JsonObject
		{
			["type"] = "array",
			["description"] = description,
			["items"] = items,
		};

		if (values.Count == 0)
		{
			// Nothing to hide on this type, and draft 04 does not allow an empty enum. "not {}" rejects any item in every
			// validator; maxItems gives editors the clearer message.
			list["items"] = new JsonObject { ["not"] = new JsonObject() };
			list["maxItems"] = 0;
			return list;
		}

		items["enum"] = new JsonArray([.. values.Select(value => (JsonNode)JsonValue.Create(value.Value))]);
		items["enumDescriptions"] = new JsonArray([.. values.Select(value => (JsonNode)JsonValue.Create(value.Description))]);
		return list;
	}

	private static void ListRootNodes(JsonObject siteProperties, AliasSchemaRoot[] roots)
	{
		if (roots.Length == 0)
		{
			return;
		}

		JsonObject key = siteProperties["RootNodeKey"]!.AsObject();
		key["type"] = "string";
		key["enum"] = new JsonArray([.. roots.Select(root => (JsonNode)JsonValue.Create(root.Key.ToString("D")))]);
		key["enumDescriptions"] = new JsonArray([.. roots.Select(root => (JsonNode)JsonValue.Create(string.IsNullOrWhiteSpace(root.Name) ? "(no name)" : root.Name))]);

		// The package matches a name case-insensitively, so a name lists every root that has it.
		IGrouping<string, AliasSchemaRoot>[] named = roots
			.Where(root => !string.IsNullOrWhiteSpace(root.Name))
			.GroupBy(root => root.Name!.Trim(), StringComparer.OrdinalIgnoreCase)
			.ToArray();
		if (named.Length == 0)
		{
			return;
		}

		JsonObject name = siteProperties["RootNodeName"]!.AsObject();
		name["type"] = "string";
		name["enum"] = new JsonArray([.. named.Select(group => (JsonNode)JsonValue.Create(group.First().Name!))]);
		name["enumDescriptions"] = new JsonArray([.. named.Select(group => (JsonNode)JsonValue.Create(string.Join(", ", group.Select(root => root.Key.ToString("D")))))]);
	}
}
